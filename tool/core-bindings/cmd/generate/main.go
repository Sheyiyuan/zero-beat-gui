// Generate Dart codecs and parity fixtures from the explicit Go wire contract.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/sheyiyuan/zero-beat-gui/wire"
)

var enumTypes = map[string]bool{}

func main() {
	check := flag.Bool("check", false, "fail if generated artifacts differ")
	output := flag.String("out", "packages/zero_beat_core", "package path, relative to GUI root")
	dart := flag.String("dart", "", "Dart executable; defaults to DART env or dart in PATH")
	flag.Parse()
	if *dart == "" {
		*dart = os.Getenv("DART")
	}
	if *dart == "" {
		*dart = "dart"
	}
	for _, e := range wire.Enums {
		enumTypes[e.Name] = true
	}
	public := header() + "import 'codec.dart';\n\nconst int coreSchemaVersion = " + fmt.Sprint(wire.SchemaVersion) + ";\n\n"
	for _, e := range wire.Enums {
		public += enumCode(e)
	}
	public += "abstract final class SourceCapability {\n"
	for _, c := range wire.Capabilities {
		public += fmt.Sprintf("  static const String %s = '%s';\n", camel(c.Name), c.Name)
	}
	public += "}\n\n"
	engine := header() + "import 'codec.dart';\n\n"
	decoder := header() + "import '../lib/zero_beat_core.dart';\nimport '../lib/engine_contract.dart';\n\nMap<String, Object?> roundTripFixture(String type, Map<String, Object?> value) {\n  return switch (type) {\n"
	for _, t := range wire.Types {
		code := classCode(t)
		if t.Name() == "EngineStream" {
			engine += code
		} else {
			public += code
		}
		decoder += fmt.Sprintf("    '%s' => %s.fromJson(value).toJson(),\n", t.Name(), t.Name())
	}
	decoder += "    _ => throw FormatException('Unknown fixture type: $type'),\n  };\n}\n"
	fixtures := wire.Fixtures()
	for _, f := range fixtures {
		if _, err := wire.Marshal(f.Value); err != nil {
			panic(fmt.Sprintf("invalid fixture %s: %v", f.Name, err))
		}
	}
	artifacts := map[string][]byte{
		"lib/src/models.g.dart":        formatDart(*dart, public),
		"lib/src/engine_models.g.dart": formatDart(*dart, engine),
		"test/fixture_decoders.g.dart": formatDart(*dart, decoder),
		"test/fixtures/core.json":      jsonBytes(map[string]any{"schema_version": wire.SchemaVersion, "fixtures": fixtures}),
		"schema.json":                  schema(),
	}
	changed := false
	for name, data := range artifacts {
		path := filepath.Join(*output, name)
		existing, _ := os.ReadFile(path)
		if bytes.Equal(existing, data) {
			continue
		}
		if *check {
			fmt.Fprintln(os.Stderr, "generated artifact differs:", path)
			changed = true
			continue
		}
		must(os.MkdirAll(filepath.Dir(path), 0755))
		must(os.WriteFile(path, data, 0644))
	}
	if changed {
		os.Exit(1)
	}
	if *check {
		fmt.Println("Dart bindings, core shape fingerprint, and parity fixtures are current.")
	} else {
		fmt.Println("Generated Dart bindings and parity fixtures.")
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func jsonBytes(v any) []byte {
	b, err := json.MarshalIndent(v, "", "  ")
	must(err)
	return append(b, '\n')
}
func header() string {
	return "// GENERATED by tool/core-bindings/cmd/generate. DO NOT EDIT.\n// Wire schema 1; no RPC transport or Session implementation.\n\n"
}
func formatDart(dart, code string) []byte {
	f, err := os.CreateTemp("", "zero-bindings-*.dart")
	must(err)
	defer os.Remove(f.Name())
	_, err = f.WriteString(code)
	must(err)
	must(f.Close())
	cmd := exec.Command(dart, "format", "--output=show", "--summary=none", f.Name())
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	b, err := cmd.Output()
	if err != nil {
		panic(fmt.Sprintf("dart format: %v: %s", err, stderr.String()))
	}
	return b
}
func camel(v string) string {
	words := strings.FieldsFunc(v, func(c rune) bool { return c == '_' || c == '-' })
	for i := 1; i < len(words); i++ {
		words[i] = strings.ToUpper(words[i][:1]) + words[i][1:]
	}
	return strings.Join(words, "")
}
func enumCode(e wire.Enum) string {
	var b strings.Builder
	fmt.Fprintf(&b, "final class %s {\n  const %s(this.value);\n  final String value;\n", e.Name, e.Name)
	for _, v := range e.Values {
		c := camel(v)
		c = "value" + strings.ToUpper(c[:1]) + c[1:]
		fmt.Fprintf(&b, "  static const %s = %s('%s');\n", c, e.Name, v)
	}
	b.WriteString("  static const Set<String> knownValues = {")
	for _, v := range e.Values {
		fmt.Fprintf(&b, "'%s',", v)
	}
	b.WriteString("};\n")
	fmt.Fprintf(&b, "  bool get isKnown => knownValues.contains(value);\n  @override\n  bool operator ==(Object other) => other is %s && value == other.value;\n  @override\n  int get hashCode => value.hashCode;\n  @override\n  String toString() => value;\n}\n\n", e.Name)
	return b.String()
}
func dartType(t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		return dartType(t.Elem()) + "?"
	}
	switch t.Name() {
	case "Decimal":
		return "BigInt"
	case "Timestamp":
		return "DateTime"
	}
	if enumTypes[t.Name()] {
		return t.Name()
	}
	switch t.Kind() {
	case reflect.String:
		return "String"
	case reflect.Bool:
		return "bool"
	case reflect.Int, reflect.Int64:
		return "int"
	case reflect.Float64:
		return "double"
	case reflect.Struct:
		return t.Name()
	case reflect.Slice:
		return "List<" + dartType(t.Elem()) + ">"
	case reflect.Map:
		return "Map<String, String>"
	}
	panic("unsupported type " + t.String())
}
func decode(t reflect.Type, expr, path string) string {
	if t.Kind() == reflect.Pointer {
		return expr + " == null ? null : " + decode(t.Elem(), expr, path)
	}
	switch t.Name() {
	case "Decimal":
		return "readDecimal(" + expr + ", '" + path + "')"
	case "Timestamp":
		return "readTimestamp(" + expr + ", '" + path + "')"
	}
	if enumTypes[t.Name()] {
		return t.Name() + "(readString(" + expr + ", '" + path + "'))"
	}
	switch t.Kind() {
	case reflect.String:
		return "readString(" + expr + ", '" + path + "')"
	case reflect.Bool:
		return "readBool(" + expr + ", '" + path + "')"
	case reflect.Int, reflect.Int64:
		return "readInt(" + expr + ", '" + path + "')"
	case reflect.Float64:
		return "readDouble(" + expr + ", '" + path + "')"
	case reflect.Struct:
		return t.Name() + ".fromJson(readObject(" + expr + ", '" + path + "'))"
	case reflect.Slice:
		return "readList(" + expr + ", '" + path + "').map((item) => " + decode(t.Elem(), "item", path+"[]") + ").toList()"
	case reflect.Map:
		return "readStringMap(" + expr + ", '" + path + "')"
	}
	panic("unsupported decode " + t.String())
}
func encode(t reflect.Type, expr string) string {
	if t.Kind() == reflect.Pointer {
		return expr + " == null ? null : " + encode(t.Elem(), expr+"!")
	}
	switch t.Name() {
	case "Decimal":
		return "writeDecimal(" + expr + ")"
	case "Timestamp":
		return "writeTimestamp(" + expr + ")"
	}
	if enumTypes[t.Name()] {
		return expr + ".value"
	}
	switch t.Kind() {
	case reflect.Struct:
		return expr + ".toJson()"
	case reflect.Slice:
		return expr + ".map((item) => " + encode(t.Elem(), "item") + ").toList()"
	case reflect.Int, reflect.Int64:
		return "writeInt(" + expr + ")"
	case reflect.Float64:
		return "writeDouble(" + expr + ")"
	default:
		return expr
	}
}
func classCode(t reflect.Type) string {
	var b strings.Builder
	fmt.Fprintf(&b, "final class %s {\n", t.Name())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		fmt.Fprintf(&b, "  final %s %s;\n", dartType(f.Type), camel(f.Tag.Get("json")))
	}
	fmt.Fprintf(&b, "  %s({\n", t.Name())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		req := "required "
		if f.Type.Kind() == reflect.Pointer {
			req = ""
		}
		fmt.Fprintf(&b, "    %s%s %s,\n", req, dartType(f.Type), camel(f.Tag.Get("json")))
	}
	b.WriteString("  }) : ")
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		n := camel(f.Tag.Get("json"))
		value := n
		if f.Type.Kind() == reflect.Slice {
			value = dartType(f.Type) + ".unmodifiable(" + n + ")"
		}
		if f.Type.Kind() == reflect.Map {
			value = "Map<String, String>.unmodifiable(" + n + ")"
		}
		if i > 0 {
			b.WriteString(",\n       ")
		}
		fmt.Fprintf(&b, "%s = %s", n, value)
	}
	if t.Name() == "BrowseEntry" {
		b.WriteString(" {\n    if ((ref == null) == (track == null)) {\n      throw const FormatException('BrowseEntry: exactly one of ref and track is required');\n    }\n  }\n")
	} else {
		b.WriteString(";\n")
	}
	fmt.Fprintf(&b, "  factory %s.fromJson(Map<String, Object?> json) => %s(\n", t.Name(), t.Name())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		key := f.Tag.Get("json")
		fmt.Fprintf(&b, "    %s: %s,\n", camel(key), decode(f.Type, "json['"+key+"']", t.Name()+"."+key))
	}
	b.WriteString("  );\n")
	b.WriteString("  Map<String, Object?> toJson() => {\n")
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		key := f.Tag.Get("json")
		fmt.Fprintf(&b, "    '%s': %s,\n", key, encode(f.Type, camel(key)))
	}
	b.WriteString("  };\n}\n\n")
	return b.String()
}
func schema() []byte {
	type field struct {
		Name string `json:"name"`
		Type string `json:"type"`
	}
	wireTypes := map[string][]field{}
	coreTypes := map[string][]field{}
	for _, t := range wire.Types {
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			wireTypes[t.Name()] = append(wireTypes[t.Name()], field{f.Tag.Get("json"), f.Type.String()})
		}
	}
	for _, t := range wire.CoreTypes {
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			if f.IsExported() {
				coreTypes[t.PkgPath()+"."+t.Name()] = append(coreTypes[t.PkgPath()+"."+t.Name()], field{f.Name, f.Type.String()})
			}
		}
	}
	return jsonBytes(map[string]any{"schema_version": wire.SchemaVersion, "wire_types": wireTypes, "core_shapes": coreTypes, "enums": wire.Enums, "capabilities": wire.Capabilities})
}
